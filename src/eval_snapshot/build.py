#!/usr/bin/env python3
"""Stage 26-eval — frozen evaluation snapshot.

Reads  data/25-final/mcqs.json
Writes data/26-eval/mcqs.json
       data/26-eval/stats.json

This is the evaluation-facing snapshot. Records keep their ORIGINAL ids and
ORIGINAL order, so locked evaluation results (output/lm_eval/, output/<lang>/)
join back to questions by ``id`` exactly as they did when the runs were made.
It is never published — the public Hugging Face release is the separate, sorted
+ renumbered stage 27-hf (see src/hf/build.py).

Option repair
-------------
159 records reach Stage 25 carrying five options instead of four (they survived
the Stage 10 structural filter), and the answer-position shuffle in
``src/final/build.py`` then permutes the gold answer across *all* option slots —
so for 42 of them the gold key landed on ``E``. Both prompt templates and the
lm-eval ``doc_to_text`` render only A-D, so those 42 items are unanswerable by
construction and were scored wrong for every model in every run.

This stage repairs that:

  * records whose ``correct_key`` is not one of A-D are DROPPED (42 records);
  * records that still carry a fifth option keep only A-D (117 records).

Both operations are order-preserving and leave the id, question, A-D option
texts, and correct_key of every surviving record byte-identical, so the frozen
prediction files remain valid — they simply no longer contain the dropped ids.
Truncating the 117 is provably inert: across all 60 runs no prediction ever
resolves to key ``E`` (the parser in src/analysis/eval.py cannot emit it).

The defect itself lives upstream in ``src/final/build.py``; it is repaired here
rather than there because re-running Stage 25 would shift its RNG stream and
re-shuffle every item's options, invalidating all 60 locked evaluation runs.

The flattened lm-eval input (mcqs_eval.jsonl) and the few-shot pool
(mcqs_dev.json) live alongside this file; mcqs_eval.jsonl is regenerated by
scripts/prep_lm_eval.py from data/26-eval/mcqs.json.

Released schema (every record exactly these keys, in this order):
  id, question, options, correct_key, domain, subdomain, level,
  length_tier, source

Usage:
    python src/eval_snapshot/build.py
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
SRC = REPO_ROOT / "data" / "25-final" / "mcqs.json"
DST_DIR = REPO_ROOT / "data" / "26-eval"
DST_MCQS = DST_DIR / "mcqs.json"
DST_STATS = DST_DIR / "stats.json"

KEEP_KEYS = (
    "id",
    "question",
    "options",
    "correct_key",
    "domain",
    "subdomain",
    "level",
    "length_tier",
    "source",
)

# The only option slots any prompt template renders.
VALID_KEYS = ("A", "B", "C", "D")


def repair_options(rows: list[dict]) -> tuple[list[dict], list[int], list[int]]:
    """Drop items whose gold answer is outside A-D; trim extra option slots.

    Returns ``(kept, dropped_ids, trimmed_ids)``. Order is preserved and no
    surviving record's id, question, A-D options, or correct_key is modified.
    """
    kept: list[dict] = []
    dropped: list[int] = []
    trimmed: list[int] = []
    for rec in rows:
        if rec.get("correct_key") not in VALID_KEYS:
            dropped.append(rec["id"])
            continue
        options = rec.get("options") or {}
        if set(options) - set(VALID_KEYS):
            rec = {**rec, "options": {k: options[k] for k in VALID_KEYS}}
            trimmed.append(rec["id"])
        kept.append(rec)
    return kept, dropped, trimmed


def compute_stats(out: list[dict]) -> dict:
    domain = Counter(r["domain"] for r in out)
    subdomain = Counter((r["domain"], r["subdomain"]) for r in out)
    level = Counter(r["level"] for r in out)
    length_tier = Counter(r["length_tier"] for r in out)
    correct_key = Counter(r["correct_key"] for r in out)

    source_name = Counter()
    for r in out:
        for s in r["source"] or []:
            source_name[s["name"]] += 1

    level_by_domain: dict[str, Counter] = defaultdict(Counter)
    for r in out:
        level_by_domain[r["domain"]][r["level"]] += 1

    return {
        "total": len(out),
        "domain_distribution": dict(domain.most_common()),
        "subdomain_distribution": {f"{d} / {s}": c for (d, s), c in subdomain.most_common()},
        "level_distribution": {k: level[k] for k in ("SSC-I", "SSC-II", "HSSC-I", "HSSC-II") if k in level},
        "level_by_domain": {
            d: {k: level_by_domain[d][k] for k in ("SSC-I", "SSC-II", "HSSC-I", "HSSC-II") if k in level_by_domain[d]}
            for d in domain
        },
        "length_tier_distribution": dict(length_tier.most_common()),
        "correct_key_distribution": dict(sorted(correct_key.items())),
        "source_distribution": dict(source_name.most_common()),
    }


def main() -> None:
    rows = json.load(open(SRC, encoding="utf-8"))
    out = [{k: rec.get(k) for k in KEEP_KEYS} for rec in rows]  # ids + order untouched
    out, dropped_ids, trimmed_ids = repair_options(out)

    stats = compute_stats(out)
    stats["option_repair"] = {
        "input_rows": len(rows),
        "dropped_gold_outside_abcd": len(dropped_ids),
        "trimmed_to_four_options": len(trimmed_ids),
        "dropped_ids": dropped_ids,
    }

    DST_DIR.mkdir(parents=True, exist_ok=True)
    with open(DST_MCQS, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)

    with open(DST_STATS, "w", encoding="utf-8") as f:
        json.dump(stats, f, ensure_ascii=False, indent=2)

    print(f"Option repair: {len(rows):,} in -> {len(out):,} out "
          f"({len(dropped_ids)} dropped, {len(trimmed_ids)} trimmed to A-D)")
    print(f"Wrote {DST_MCQS.relative_to(REPO_ROOT)} ({len(out):,} records, ids unchanged)")
    print(f"Wrote {DST_STATS.relative_to(REPO_ROOT)}")
    print(f"Keys per record: {list(out[0].keys())}")


if __name__ == "__main__":
    main()
