def load_csv() -> dict[tuple[str, str], dict]:
    with open(CSV_PATH, encoding="utf-8") as f:
        return {(r["model"], r["language"]): r for r in csv.DictReader(f)}


def fmt_invalid(rate: float) -> str:
    """Invalid-output rate, matching the paper's existing convention."""
    if rate == 0:
        return "0"
    if rate < 0.1:
        return r"$<$0.1"
    return f"{rate:.1f}"


def zero_shot_table(rows: dict[tuple[str, str], dict]) -> str:
    # Per (language, column): best value within each group, and globally.
    best_in_group: dict[tuple[str, str, int], float] = {}
    best_global: dict[tuple[str, str], float] = {}
    for gi, (_, models) in enumerate(GROUPS):
        for lang in LANGS:
            for col, _ in COLUMNS:
                vals = [float(rows[(m, lang)][col]) for m, _ in models]
                best_in_group[(lang, col, gi)] = max(vals)
                best_global[(lang, col)] = max(best_global.get((lang, col), -1), max(vals))

    def cell(model: str, lang: str, col: str, gi: int) -> str:
        v = float(rows[(model, lang)][col])
        s = f"{v:.2f}"
        if v == best_global[(lang, col)]:
            return r"\fbox{\textbf{" + s + "}}"
        if v == best_in_group[(lang, col, gi)]:
            return r"\textbf{" + s + "}"
        return s

    out: list[str] = [
        r"% GENERATED by src/analysis/make_tables.py -- do not edit by hand.",
        r"% Accuracy is all-item exact match (invalid outputs scored wrong) over",
        r"% the 26,389 released items. Rebuild: python src/analysis/eval.py --detailed",
        r"%                                     python src/analysis/make_tables.py",
        r"\begin{table*}[t]",
        r"\centering",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{l *{7}{r} c *{7}{r}}",
        r"\toprule",
        r"\multirow{2}{*}{\textbf{Model}} &",
        r"\multicolumn{7}{c}{\textbf{English Prompt (Accuracy \% $\uparrow$)}} &&",
        r"\multicolumn{7}{c}{\textbf{Urdu Prompt (Accuracy \% $\uparrow$)}} \\",
        r"\cmidrule(lr){2-8}\cmidrule(lr){10-16}",
        r"& \textbf{STEM} & \textbf{H} & \textbf{SS} & \textbf{P} & \textbf{O} & "
        r"\textbf{Overall} & \textbf{Inv\%}\,$\downarrow$ &&",
        r"  \textbf{STEM} & \textbf{H} & \textbf{SS} & \textbf{P} & \textbf{O} & "
        r"\textbf{Overall} & \textbf{Inv\%}\,$\downarrow$ \\",
    ]

    for gi, (heading, models) in enumerate(GROUPS):
        out += [
            r"\midrule",
            r"\rowcolor{softgray}",
            r"\multicolumn{16}{c}{\textbf{" + heading + r"}} \\",
            r"\midrule",
        ]
        for model, display in models:
            parts = []
            for lang in LANGS:
                cells = [cell(model, lang, col, gi) for col, _ in COLUMNS]
                cells.append(fmt_invalid(float(rows[(model, lang)]["invalid_rate"])))
                parts.append(" & ".join(cells))
            out.append(display)
            out.append(f"  & {parts[0]} &&")
            out.append(f"    {parts[1]} \\\\")

    out += [
        r"\bottomrule",
        r"\end{tabular}%",
        r"}",
        r"\caption{\textbf{Model performance on \ds{}.} All-item accuracy (\%) under "
        r"English and Urdu prompts across five domains and overall, over all "
        r"$26{,}389$ benchmark items. An unparsable, malformed, or error output is "
        r"scored as incorrect, so \textbf{Overall} is directly comparable across "
        r"models regardless of how reliably they follow the response format. "
        r"\textbf{Inv\%} reports that invalid-output rate separately (lower is "
        r"better). Boxed values mark the best score per column, while bold values "
        r"indicate the best score within each model group.}",
        r"\label{tab:modelperformance}",
        r"\end{table*}",
    ]
    return "\n".join(out) + "\n"


# ── Table 5: few-shot ─────────────────────────────────────────────────────────
#
# The 0-shot column comes from the generation pipeline (output/<lang>/) and the
# 1/3/5-shot columns from lm-evaluation-harness (output/lm_eval/). Every column
# is scored on the SAME population: the 26,389 released items minus the 130
# demonstration-pool items, i.e. 26,259.
#
# The 130 are dropped from the 0-shot column too, even though a zero-shot prompt
# shows no demonstrations. A shot-to-shot delta is only meaningful if both ends
# cover the same items, and mixing populations within one comparison table is a
# worse defect than the 0.05-point gap this opens against Table 4, which scores
# all 26,389. The caption states both numbers.

FEWSHOT_MODELS = [
    ("meta-llama__Llama-3.1-8B-Instruct", "LLaMA-3.1-8B"),
    ("google__gemma-3-4b-it", "Gemma-3-4B-IT"),
    ("Qwen__Qwen3-8B", "Qwen3-8B"),
    ("Qwen__Qwen3-4B-Instruct-2507", "Qwen3-4B-Instruct-2507"),
]
SHOTS = ("1shot", "3shot", "5shot")


def fewshot_accuracies() -> tuple[dict[tuple[str, str, str], float], int]:
    """Return {(model, lang, shot): accuracy%} plus the shared population size.

    ``shot`` is "0shot" for the generation pipeline, or 1/3/5shot for lm_eval.
    Every setting is scored on the same 26,259 items so the deltas compare like
    with like; the size is returned rather than hardcoded, and a mismatch across
    runs is a hard error.
    """
    keep = released_ids() - fewshot_pool_ids()
    acc: dict[tuple[str, str, str], float] = {}
    sizes = set()
    for lang in LANGS:
        for model, _ in FEWSHOT_MODELS:
            path = OUTPUT_DIR / lang / model / "predictions.json"
            recs = json.loads(path.read_text(encoding="utf-8"))
            st = evaluate(recs, restrict_ids=keep)
            acc[(model, lang, "0shot")] = 100 * st["accuracy"]
            sizes.add(st["scored"])
        for row in discover_lm_eval(lang, restrict_ids=keep, exclude_ids=set()):
            acc[(row["model"], lang, row["shots"])] = 100 * row["accuracy"]
            sizes.add(row["scored"])
    if len(sizes) != 1:
        raise SystemExit(f"population mismatch across runs: {sorted(sizes)}")
    return acc, sizes.pop()


def _delta(value: float, base: float) -> str:
    d = value - base
    colour = "darkgreen" if d >= 0 else "darkred"
    sign = "+" if d >= 0 else "-"
    return (f"{value:.2f}\\,\\textcolor{{{colour}}}{{\\scriptsize"
            f"($ {sign} ${abs(d):.2f})}}".replace("$ ", "$").replace(" $", "$"))


def few_shot_table(acc: dict[tuple[str, str, str], float], n: int,
                   rows: dict[tuple[str, str], dict]) -> str:
    # Largest gap between this table's 0-shot column and Table 4's Overall,
    # computed rather than asserted so the caption cannot drift.
    drift = max(abs(acc[(m, l, "0shot")] - float(rows[(m, l)]["total_accuracy"]))
                for m, _ in FEWSHOT_MODELS for l in LANGS)
    out: list[str] = [
        r"% GENERATED by src/analysis/make_tables.py -- do not edit by hand.",
        rf"% All columns scored on the same {n:,} items: the 26,389 released items",
        r"% minus the 130 few-shot demonstration items. Rebuild:",
        r"%   python src/analysis/eval.py --detailed && python src/analysis/make_tables.py",
        r"\begin{table*}[!t]",
        r"\centering",
        r"\small",
        r"\renewcommand{\arraystretch}{1}",
        r"",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{@{}l *{4}{c} c *{4}{c}@{}}",
        r"\toprule",
        r"\multirow{2}{*}{\textbf{Model}} &",
        r"\multicolumn{4}{c}{\textbf{English Prompt (Accuracy \% $\uparrow$)}} &&",
        r"\multicolumn{4}{c}{\textbf{Urdu Prompt (Accuracy \% $\uparrow$)}} \\",
        r"\cmidrule(lr){2-5}",
        r"\cmidrule(lr){7-10}",
        r"& \textbf{0-shot}",
        r"& \textbf{1-shot}",
        r"& \textbf{3-shot}",
        r"& \textbf{5-shot}",
        r"&& \textbf{0-shot}",
        r"& \textbf{1-shot}",
        r"& \textbf{3-shot}",
        r"& \textbf{5-shot} \\",
        r"\midrule",
        r"",
        r"\rowcolor{softgray}",
        r"\multicolumn{10}{c}{\textbf{Evaluated Open-weight Models}} \\",
        r"\midrule",
        r"",
    ]

    for model, display in FEWSHOT_MODELS:
        out.append(display)
        for i, lang in enumerate(LANGS):
            base = acc[(model, lang, "0shot")]
            prefix = "&& " if i else "& "
            out.append(f"{prefix}{base:.2f}")
            for shot in SHOTS:
                out.append(f"& {_delta(acc[(model, lang, shot)], base)}")
        out[-1] += r" \\"
        out.append("")

    out += [r"\midrule", r"\textbf{Mean}"]
    for i, lang in enumerate(LANGS):
        mean0 = sum(acc[(m, lang, "0shot")] for m, _ in FEWSHOT_MODELS) / len(FEWSHOT_MODELS)
        prefix = "&& " if i else "& "
        out.append(f"{prefix}\\textbf{{{mean0:.2f}}}")
        for shot in SHOTS:
            mean = sum(acc[(m, lang, shot)] for m, _ in FEWSHOT_MODELS) / len(FEWSHOT_MODELS)
            out.append("& \\textbf{" + _delta(mean, mean0) + "}")
    out[-1] += r" \\"

    out += [
        r"",
        r"\bottomrule",
        r"\end{tabular}%",
        r"}",
        r"",
        r"\caption{\textbf{Few-shot performance on \ds{}.} All-item accuracy (\%) at "
        r"$0$-, $1$-, $3$-, and $5$-shot under English and Urdu instruction prompts. "
        rf"All columns are scored on the same ${n // 1000}{{,}}{n % 1000:03d}$ items --- the "
        r"benchmark minus the $130$ held-out demonstration items --- so the shot "
        r"settings are directly comparable. The $0$-shot figures therefore differ "
        rf"by at most ${drift:.2f}$ points from the corresponding entries in "
        r"Table~\ref{tab:modelperformance}, which scores all $26{,}389$ items. "
        r"Deltas are relative to the corresponding $0$-shot baseline, with "
        r"\textcolor{darkgreen}{green} indicating gains and \textcolor{darkred}{red} "
        r"indicating losses. Mean values aggregate the four models.}",
        r"\label{tab:fewshot}",
        r"\end{table*}",
    ]
    return "\n".join(out) + "\n"


# ── Table 16: STEM-Humanities gap (Urdu prompt) ───────────────────────────────


def stem_hum_gap_table(rows: dict[tuple[str, str], dict]) -> str:
    out: list[str] = [
        r"% GENERATED by src/analysis/make_tables.py -- do not edit by hand.",
        r"\begin{table}[!t]",
        r"\centering",
        r"\small",
        r"\renewcommand{\arraystretch}{1.1}",
        r"\begin{tabular*}{\columnwidth}{@{\extracolsep{\fill}}lrrr}",
        r"\toprule",
        r"\textbf{Model} & \textbf{STEM} & \textbf{Humanities} & \textbf{Gap} \\",
    ]
    for heading, models in GROUPS:
        out += [
            r"\midrule",
            r"\rowcolor{softgray}",
            r"\multicolumn{4}{c}{\textbf{" + heading + r"}} \\",
            r"\midrule",
        ]
        for model, display in models:
            r = rows[(model, "ur")]
            stem, hum = float(r["STEM_accuracy"]), float(r["Humanities_accuracy"])
            gap = stem - hum
            gap_tex = f"{gap:.2f}" if gap >= 0 else f"$-${abs(gap):.2f}"
            out += [display, f"& {stem:.2f}", f"& {hum:.2f}",
                    f"& {gap_tex} \\\\"]
    out += [
        r"\bottomrule",
        r"\end{tabular*}",
        r"\caption{\textbf{STEM--Humanities gap under the Urdu prompt.} All-item accuracy "
        r"(\%) and their difference in percentage points, in the roster order of "
        r"Table~\ref{tab:language-models}. Small or negative gaps reflect near-chance "
        r"performance in both domains for BLOOMZ, or comparatively low STEM accuracy for "
        r"Qalb and Alif. Values are taken from Table~\ref{tab:modelperformance}.}",
        r"\label{tab:stem-hum-gap}",
        r"\end{table}",
    ]
    return "\n".join(out) + "\n"


# -- Tables 17/18: per-subdomain accuracy -------------------------------------
#
# Column order is by subdomain size within each domain (descending), matching
# the acronym table in the appendix. The order is asserted against the data so
# the header cannot silently drift out of sync with the columns.

SUBDOMAIN_ACRONYMS = {
    "chemistry": "CHM", "biology": "BIO", "general science": "GSC",
    "mathematics": "MTH", "computer science": "CSC", "physics": "PHY",
    "urdu literature": "ULT", "urdu language": "ULG", "islamic studies": "ISL",
    "urdu grammar": "UGR", "ethics": "ETH", "fine arts": "FNA",
    "pakistan studies": "PKS", "economics": "ECO", "education": "EDU",
    "sociology": "SOC", "health and physical education": "HPE", "civics": "CIV",
    "geography": "GEO", "psychology": "PSY",
    "current and international affairs": "CIA", "commerce": "COM",
    "psychometrics": "PMT",
    "professional development": "PRD", "professional studies": "PRS",
    "general knowledge": "GKN",
}
DOMAIN_ORDER = ["STEM", "Humanities", "Social Sciences", "Profession", "Other"]


def subdomain_layout() -> list[tuple[str, list[str]]]:
    """[(domain, [subdomain, ...])] ordered by size within each domain."""
    from collections import Counter
    rows = json.loads((REPO_ROOT / "data" / "26-eval" / "mcqs.json").read_text(encoding="utf-8"))
    counts = Counter((r["domain"], r["subdomain"]) for r in rows)
    layout = []
    for d in DOMAIN_ORDER:
        subs = sorted(((n, s) for (dd, s), n in counts.items() if dd == d), reverse=True)
        layout.append((d, [s for _, s in subs]))
    missing = [s for _, subs in layout for s in subs if s not in SUBDOMAIN_ACRONYMS]
    if missing:
        raise SystemExit(f"no acronym defined for: {missing}")
    return layout


def load_subdomain_csv() -> dict[tuple[str, str, str], float]:
    path = OUTPUT_DIR / "subdomain_accuracy.csv"
    with open(path, encoding="utf-8") as f:
        return {(r["model"], r["language"], r["subdomain"]): float(r["accuracy"])
                for r in csv.DictReader(f)}


def subdomain_table(acc: dict[tuple[str, str, str], float], lang: str) -> str:
    layout = subdomain_layout()
    flat = [s for _, subs in layout for s in subs]

    best_in_group, best_global = {}, {}
    for gi, (_, models) in enumerate(GROUPS):
        for sub in flat:
            vals = [acc[(m, lang, sub)] for m, _ in models]
            best_in_group[(sub, gi)] = max(vals)
            best_global[sub] = max(best_global.get(sub, -1.0), max(vals))

    def cell(model: str, sub: str, gi: int) -> str:
        v = acc[(model, lang, sub)]
        out = f"{v:.2f}"
        if v == best_global[sub]:
            return r"\fbox{\textbf{" + out + "}}"
        if v == best_in_group[(sub, gi)]:
            return r"\textbf{" + out + "}"
        return out

    widths = "".join(f" *{{{len(subs)}}}{{r}}" for _, subs in layout)
    spans, col = [], 2
    for d, subs in layout:
        spans.append((col, col + len(subs) - 1))
        col += len(subs)
    prompt = "English" if lang == "en" else "Urdu"

    out = [
        r"% GENERATED by src/analysis/make_tables.py -- do not edit by hand.",
        r"\begin{table*}[" + ("t" if lang == "en" else "!h") + "]",
        r"\centering",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{l" + widths + "}",
        r"\toprule",
        r"\multirow{2}{*}{\textbf{Model}} &",
        " &\n".join(r"\multicolumn{%d}{c}{\textbf{%s}}" % (len(subs), d) for d, subs in layout) + r" \\",
        "".join(r"\cmidrule(lr){%d-%d}" % sp for sp in spans),
        " ".join("& " + " & ".join(r"\textbf{%s}" % SUBDOMAIN_ACRONYMS[s] for s in subs)
                 for _, subs in layout) + r" \\",
    ]
    ncol = len(flat) + 1
    for gi, (heading, models) in enumerate(GROUPS):
        out += [r"\midrule", r"\rowcolor{softgray}",
                r"\multicolumn{%d}{c}{\textbf{%s}} \\" % (ncol, heading), r"\midrule"]
        for model, display in models:
            out.append(display)
            for _, subs in layout:
                out.append("  & " + " & ".join(cell(model, s, gi) for s in subs))
            out[-1] += r" \\"
    out += [
        r"\bottomrule",
        r"\end{tabular}%",
        r"}",
        r"\caption{\textbf{Subdomain-level model performance on \ds{} under the "
        + prompt + r" prompt.} All-item accuracy (\%) across all 26 subdomains grouped "
        r"by domain, with unparsable outputs scored as incorrect. Subdomains are ordered "
        r"within each domain by dataset size (descending); see "
        r"Table~\ref{tab:urdummlu-domains-levels} for acronym expansions. Boxed values "
        r"mark the best score per column, while bold values indicate the best score "
        r"within each model group.}",
        r"\label{tab:subdomain_performance_" + lang + "}",
        r"\end{table*}",
    ]
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stdout", action="store_true", help="print instead of writing")
    args = ap.parse_args()

    rows = load_csv()
    acc, pop = fewshot_accuracies()
    sub = load_subdomain_csv()
    outputs = {
        "0_shot_results.tex": zero_shot_table(rows),
        "few_shot_results.tex": few_shot_table(acc, pop, rows),
        "stem_hum_gap.tex": stem_hum_gap_table(rows),
        "0_shot_subdomain_en.tex": subdomain_table(sub, "en"),
        "0_shot_subdomain_ur.tex": subdomain_table(sub, "ur"),
    }
    if args.stdout:
        for name, tex in outputs.items():
            print(f"%%%%%%%%%% {name}\n{tex}")
        return
    for name, tex in outputs.items():
        dst = TABLES_DIR / name
        dst.write_text(tex, encoding="utf-8")
        print(f"Wrote {dst.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
